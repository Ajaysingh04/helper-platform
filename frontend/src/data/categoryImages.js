/**
 * Intelligently maps any category name or slug to its strictly related professional trade photos.
 * @param {string} categoryName - Category title or URL slug
 * @returns {string[]} Array of 3 high-res trade-related images
 */
export function getServicemanImagesForCategory(categoryName = "") {
  const text = String(categoryName).toLowerCase().replace(/[-_]/g, " ").trim();

  // Electricians & Electrical
  if (text.includes("electr") || text.includes("circuit") || text.includes("wiring") || text.includes("light")) {
    return CATEGORY_IMAGE_REGISTRY.electrician;
  }

  // Plumbers & Plumbing
  if (text.includes("plumb") || text.includes("pipe") || text.includes("drain") || text.includes("leak") || text.includes("tap")) {
    return CATEGORY_IMAGE_REGISTRY.plumber;
  }

  // AC & Appliances
  if (text.includes("ac ") || text.includes("air condition") || text.includes("cool") || text.includes("refrigerator") || text.includes("appliance")) {
    return CATEGORY_IMAGE_REGISTRY.ac;
  }

  // Cleaning & Sanitization
  if (text.includes("clean") || text.includes("sanitiz") || text.includes("housekeep") || text.includes("dust") || text.includes("pest")) {
    return CATEGORY_IMAGE_REGISTRY.cleaning;
  }

  // Painters & Painting
  if (text.includes("paint") || text.includes("wall") || text.includes("color") || text.includes("decor")) {
    return CATEGORY_IMAGE_REGISTRY.painter;
  }

  // Carpenters & Woodcraft
  if (text.includes("carpent") || text.includes("wood") || text.includes("furnitur") || text.includes("lock")) {
    return CATEGORY_IMAGE_REGISTRY.carpenter;
  }

  // Dentists
  if (text.includes("dent")) {
    return CATEGORY_IMAGE_REGISTRY.dentist;
  }

  // Medical, Doctors, Clinics, Hospitals & Specialists
  if (
    text.includes("doctor") || 
    text.includes("physician") || 
    text.includes("hospital") || 
    text.includes("clinic") || 
    text.includes("pathology") || 
    text.includes("sonography") || 
    text.includes("diagnostic") ||
    text.includes("dermatolog") ||
    text.includes("neurolog") ||
    text.includes("cardiolog") ||
    text.includes("paediatr") ||
    text.includes("orthopaed") ||
    text.includes("gastro") ||
    text.includes("urolog") ||
    text.includes("gynaecolog") ||
    text.includes("ophthalmolog") ||
    text.includes("ent") ||
    text.includes("physiotherap") ||
    text.includes("ayurved") ||
    text.includes("homeopath") ||
    text.includes("health")
  ) {
    return CATEGORY_IMAGE_REGISTRY.doctor;
  }

  // Chemists & Pharmacies
  if (text.includes("chemist") || text.includes("pharmac") || text.includes("medicin")) {
    return CATEGORY_IMAGE_REGISTRY.pharmacy;
  }

  // Salons, Hair Stylists & Beauty Parlours
  if (text.includes("salon") || text.includes("parlour") || text.includes("hair") || text.includes("stylist") || text.includes("beauty")) {
    return CATEGORY_IMAGE_REGISTRY.salon;
  }

  // Spa & Body Massage
  if (text.includes("spa") || text.includes("massage") || text.includes("wellness")) {
    return CATEGORY_IMAGE_REGISTRY.spa;
  }

  // Car, Bike & Auto Mechanics
  if (text.includes("car") || text.includes("bike") || text.includes("auto") || text.includes("mechanic") || text.includes("motor") || text.includes("vehicle") || text.includes("taxi")) {
    return CATEGORY_IMAGE_REGISTRY.auto;
  }

  // Food, Chef, Cooking, Bakery & Restaurants
  if (text.includes("food") || text.includes("chef") || text.includes("cook") || text.includes("baker") || text.includes("cake") || text.includes("restaurant") || text.includes("coffee") || text.includes("dining")) {
    return CATEGORY_IMAGE_REGISTRY.food;
  }

  // Groceries, Vegetables, Dmart
  if (text.includes("grocer") || text.includes("vegetable") || text.includes("fruit") || text.includes("dmart") || text.includes("supermarket") || text.includes("store")) {
    return CATEGORY_IMAGE_REGISTRY.grocery;
  }

  // Gym, Fitness & Yoga
  if (text.includes("gym") || text.includes("fitness") || text.includes("yoga") || text.includes("workout") || text.includes("trainer") || text.includes("sport")) {
    return CATEGORY_IMAGE_REGISTRY.fitness;
  }

  // Photography & Photo Studios
  if (text.includes("photo") || text.includes("studio") || text.includes("camera") || text.includes("cinema")) {
    return CATEGORY_IMAGE_REGISTRY.photography;
  }

  // Education, Teaching, Schools & Classes
  if (text.includes("teach") || text.includes("school") || text.includes("class") || text.includes("music") || text.includes("dance") || text.includes("tutor") || text.includes("book")) {
    return CATEGORY_IMAGE_REGISTRY.education;
  }

  // Packers & Movers, Logistics, Couriers
  if (text.includes("packer") || text.includes("mover") || text.includes("courier") || text.includes("shift") || text.includes("transport") || text.includes("travel")) {
    return CATEGORY_IMAGE_REGISTRY.logistics;
  }

  // Pet Shops & Pet Care
  if (text.includes("pet") || text.includes("dog") || text.includes("cat") || text.includes("vet")) {
    return CATEGORY_IMAGE_REGISTRY.pets;
  }

  // Electronics & Phone Repair
  if (text.includes("mobile") || text.includes("phone") || text.includes("laptop") || text.includes("repair") || text.includes("electronic")) {
    return CATEGORY_IMAGE_REGISTRY.electronics;
  }

  // Estate Agents & Living
  if (text.includes("estate") || text.includes("broker") || text.includes("property") || text.includes("hostel") || text.includes("pg") || text.includes("dharamshala") || text.includes("banquet")) {
    return CATEGORY_IMAGE_REGISTRY.realestate;
  }

  // Default fallback (Safe verified pro photography)
  return CATEGORY_IMAGE_REGISTRY.default;
}

/**
 * Returns a single category-specific serviceman image.
 */
export function getServicemanImage(categoryName = "", index = 0) {
  const images = getServicemanImagesForCategory(categoryName);
  return images[index % images.length] || images[0];
}
